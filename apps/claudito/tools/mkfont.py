print("static const uint8_t cl_font5x7[][5] = {")
prev = None
for ch, cols in rows:
    # rellenar huecos del rango con espacio
    if prev is not None:
        for missing in range(prev + 1, ord(ch)):
            print("    { 0x00, 0x00, 0x00, 0x00, 0x00 },   /* %d */" % missing)
    label = ch if ch != "'" else "apostrofo"
    print("    { %s },   /* '%s' */" % (", ".join("0x%02X" % c for c in cols), label))
    prev = ord(ch)
print("};")
