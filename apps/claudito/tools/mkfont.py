order = sorted(GLYPHS.keys(), key=ord)
rows = []
for ch in order:
    art = GLYPHS[ch]
    assert len(art) == 7, ch
    cols = []
    for x in range(5):
        bits = 0
        for y in range(7):
            assert len(art[y]) == 5, (ch, y)
            if art[y][x] == '#':
                bits |= (1 << y)
        cols.append(bits)
    rows.append((ch, cols))

print("/* GENERADO desde tools/mkfont.py de la app - fuente 5x7, bit n = fila n */")
print("static const uint8_t CL_FONT_FIRST = %d;" % ord(order[0]))
