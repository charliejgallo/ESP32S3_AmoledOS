/*
 * BLE - the names behind the numbers: Bluetooth SIG company identifiers,
 * 16-bit UUIDs (services, characteristics, descriptors and the members'
 * 0xFDxx/0xFExx), a few well known 128-bit vendor UUIDs, and the Appearance
 * values.
 *
 * Every table is sorted and searched by halves. Company and service names
 * are proper names (the SIG's own, in English, as people search them) and
 * are not marked for translation; the appearance names describe what a
 * thing is, so they are in Spanish and marked N_(). An id that was not
 * certain was left out on purpose: no name is better than a wrong one.
 */
#include "bl_decode.h"

#include <string.h>

typedef struct {
    uint16_t id;
    const char *name;
} name16_t;

static const char *find16(const name16_t *t, int n, uint16_t id)
{
    int lo = 0, hi = n - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (t[mid].id == id) return t[mid].name;
        if (t[mid].id < id) lo = mid + 1;
        else hi = mid - 1;
    }
    return NULL;
}

